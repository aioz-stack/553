<?php

namespace App\Console\Commands;

use App\Game\BotArranger;
use App\Game\BotStrength;
use App\Game\Deck;
use Illuminate\Console\Command;

/**
 * Measure how strong each lane of a bot arrangement really is, by self-play:
 * random deals of all 52 cards, every hand arranged by BotArranger, and the
 * strength of every Front / Middle / Back recorded. The percentiles become
 * app/Game/BotStrengthTable.php (what BotStrength::chance reads). Each pass
 * re-arranges with the previous pass's table, so the bots are calibrated
 * against opponents that play like them.
 */
class CalibrateBots extends Command
{
    protected $signature = 'pusoy:calibrate-bots {--deals=800 : random 52-card deals per pass (4 hands each)} {--passes=2} {--points=1000 : percentile points stored per lane}';

    protected $description = 'Self-play calibration of the Single Player bot lane strengths (writes app/Game/BotStrengthTable.php)';

    public function handle(): int
    {
        $deals = max(50, (int) $this->option('deals'));
        $points = max(50, (int) $this->option('points'));
        $table = null;

        for ($pass = 1; $pass <= max(1, (int) $this->option('passes')); $pass++) {
            BotStrength::use($table);
            $lanes = ['front' => [], 'middle' => [], 'back' => []];
            $this->info("Pass {$pass}: {$deals} deals");
            $bar = $this->output->createProgressBar($deals);

            for ($d = 0; $d < $deals; $d++) {
                foreach (Deck::deal(Deck::shuffled(Deck::newSeed()), 4, 13) as $hand) {
                    $a = BotArranger::arrange($hand);
                    $lanes['front'][] = BotArranger::strength($a->frontValue);
                    $lanes['middle'][] = BotArranger::strength($a->middleValue);
                    $lanes['back'][] = BotArranger::strength($a->backValue);
                }
                $bar->advance();
            }
            $bar->finish();
            $this->newLine();

            $table = [];
            foreach ($lanes as $lane => $values) {
                sort($values);
                $n = count($values);
                $table[$lane] = [];
                for ($i = 0; $i < $points; $i++) {
                    $table[$lane][] = $values[min($n - 1, intdiv(($i * 2 + 1) * $n, $points * 2))];
                }
            }
        }

        $this->write($table, $deals);
        BotStrength::use(null);
        $this->info('Wrote app/Game/BotStrengthTable.php');

        return self::SUCCESS;
    }

    /** @param  array<string, list<int>>  $table */
    private function write(array $table, int $deals): void
    {
        $rows = [];
        foreach ($table as $lane => $values) {
            $rows[] = "        '{$lane}' => [".implode(', ', $values).'],';
        }
        $body = implode("\n", $rows);
        $date = now()->toDateString();

        file_put_contents(app_path('Game/BotStrengthTable.php'), <<<PHP
<?php

namespace App\\Game;

/**
 * GENERATED by `php artisan pusoy:calibrate-bots` on {$date} ({$deals} self-play deals per pass).
 * Sorted percentile points of each lane's strength (BotArranger::strength) in bot arrangements.
 * Do not edit by hand: re-run the command after changing the arranger or the hand rules.
 */
final class BotStrengthTable
{
    public const LANES = [
{$body}
    ];
}

PHP);
    }
}
