// Converts exported art (assets/art/**.png) to WebP and writes src/art/generated.ts — the static
// require() map Metro needs. Run after re-exporting art:  npm run art:index
import { existsSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../../', import.meta.url));
const artDir = join(root, 'assets/art');
const out = join(root, 'src/art/generated.ts');

const dirs = [];
const walk = (d) => {
  for (const n of readdirSync(d)) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (n === 'manifest.json') dirs.push(d);
  }
};
walk(artDir);

let converted = 0;
const entries = [];
for (const d of dirs.sort()) {
  const m = JSON.parse(readFileSync(join(d, 'manifest.json'), 'utf8'));
  for (const l of m.layers) {
    const png = join(d, l.file);
    const webp = png.replace(/\.png$/, '.webp');
    if (existsSync(png)) {
      await sharp(png).webp({ quality: 90, alphaQuality: 100, effort: 5 }).toFile(webp);
      unlinkSync(png);
      converted++;
    }
    l.file = l.file.replace(/\.png$/, '.webp');
  }
  writeFileSync(join(d, 'manifest.json'), JSON.stringify(m, null, 1));
  const rel = relative(join(root, 'src/art'), d).replace(/\\/g, '/');
  const key = relative(artDir, d).replace(/\\/g, '/');
  const layers = m.layers
    .map((l) => {
      const { file, ...rest } = l;
      return `    { ...${JSON.stringify(rest)}, src: require('${rel}/${file}') }`;
    })
    .join(',\n');
  entries.push(`  '${key}': { width: ${m.width}, height: ${m.height}, layers: [\n${layers},\n  ] }`);
}

writeFileSync(
  out,
  `// GENERATED by scripts/art/build-index.mjs — do not edit.\n/* eslint-disable */\nimport type { ArtManifest } from './types';\n\nexport const ART: Record<string, ArtManifest> = {\n${entries.join(',\n')},\n};\n`,
);
console.log(`art: ${dirs.length} pieces, ${converted} PNG → WebP, wrote src/art/generated.ts`);
